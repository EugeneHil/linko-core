#!/usr/bin/env python3
"""Generate Tokens.swift from design-tokens/tokens.json.

Single source of truth: tokens.json (spec §4.8). Stdlib only, stock macOS
Python 3.9 compatible. Output is deterministic byte-for-byte: every JSON
key iteration is sorted.

Usage:
    python3 design-tokens/generate.py                 # write Tokens.swift
    python3 design-tokens/generate.py --check         # exit 1 + diff if stale
    python3 design-tokens/generate.py --swift-out P   # custom output path
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_SWIFT_OUT = HERE / "Tokens.swift"

SECTION_NAMES = ("colors", "typography", "spacing", "radii", "controlSizes")
COLOR_SCHEMES = ("light", "dark")
TYPOGRAPHY_SECTIONS = ("fontSize", "fontWeight", "lineHeight")
TRAY_KEYS = ("button", "gap", "screenEdge")
# CSS-weight scale mapped to SwiftUI Font.Weight cases.
FONT_WEIGHTS = {
    100: "thin",
    200: "ultralight",
    300: "light",
    400: "regular",
    500: "medium",
    600: "semibold",
    700: "bold",
    800: "heavy",
    900: "black",
}
HEX_COLOR_RE = re.compile(r"^#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$")

HEADER = """\
//
//  Tokens.swift
//  Linko design tokens
//
//  Generated by design-tokens/generate.py — do not edit.
//  Source of truth: design-tokens/tokens.json
//
"""


class TokenError(Exception):
    """Raised when tokens.json violates the design-token contract."""


def validate_tokens(data: object) -> dict:
    """Validate the parsed tokens.json; return it unchanged."""
    if not isinstance(data, dict):
        raise TokenError("tokens.json must be a JSON object")
    unknown = sorted(set(data) - set(SECTION_NAMES))
    if unknown:
        raise TokenError(
            f"unknown section(s) {', '.join(unknown)}; "
            f"allowed: {', '.join(SECTION_NAMES)}"
        )
    missing = [s for s in SECTION_NAMES if s not in data]
    if missing:
        raise TokenError(f"missing section(s): {', '.join(missing)}")

    colors = data["colors"]
    if not isinstance(colors, dict) or not colors:
        raise TokenError("colors must be a non-empty object")
    for name, value in sorted(colors.items()):
        if not isinstance(value, dict) or set(value) != set(COLOR_SCHEMES):
            raise TokenError(f"color {name!r} must have exactly light and dark")
        for scheme in COLOR_SCHEMES:
            if not isinstance(value[scheme], str) or not HEX_COLOR_RE.match(
                value[scheme]
            ):
                raise TokenError(
                    f"color {name!r} {scheme} must be #RRGGBB or #RRGGBBAA"
                )

    typography = data["typography"]
    if not isinstance(typography, dict):
        raise TokenError("typography must be an object")
    unknown_typo = sorted(set(typography) - set(TYPOGRAPHY_SECTIONS))
    if unknown_typo:
        raise TokenError(
            f"unknown typography section(s) {', '.join(unknown_typo)}; "
            f"allowed: {', '.join(TYPOGRAPHY_SECTIONS)}"
        )
    missing_typo = [s for s in TYPOGRAPHY_SECTIONS if s not in typography]
    if missing_typo:
        raise TokenError(f"missing typography section(s): {missing_typo}")
    for section in TYPOGRAPHY_SECTIONS:
        scale = typography[section]
        if not isinstance(scale, dict) or not scale:
            raise TokenError(f"typography.{section} must be a non-empty object")
        for name, value in sorted(scale.items()):
            if not _is_number(value):
                raise TokenError(f"typography.{section}.{name} must be a number")
    for name, value in sorted(typography["fontWeight"].items()):
        if not isinstance(value, int) or value not in FONT_WEIGHTS:
            raise TokenError(
                f"typography.fontWeight.{name} must be one of: "
                f"{', '.join(str(w) for w in sorted(FONT_WEIGHTS))}"
            )

    for section in ("spacing", "radii", "controlSizes"):
        values = data[section]
        if not isinstance(values, dict) or not values:
            raise TokenError(f"{section} must be a non-empty object")
        for name, value in sorted(values.items()):
            if not _is_number(value) or value <= 0:
                raise TokenError(f"{section}.{name} must be a positive number")
    for name, value in sorted(data["spacing"].items()):
        if not isinstance(value, int) or value % 4 != 0:
            raise TokenError(f"spacing.{name} must be an int on the 4-pt grid")
    missing_tray = [k for k in TRAY_KEYS if k not in data["controlSizes"]]
    if missing_tray:
        raise TokenError(f"controlSizes must define {', '.join(TRAY_KEYS)}")

    return data


def _is_number(value: object) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _swift_number(value: object) -> str:
    """Format a JSON number as a Swift literal (12 -> '12', 1.21 -> '1.21')."""
    if isinstance(value, int):
        return str(value)
    text = f"{float(value):.6f}".rstrip("0").rstrip(".")
    return text if text else "0"


def _swift_color(hex_color: str) -> str:
    """Render #RRGGBB[AA] as a SwiftUI Color literal."""
    r = int(hex_color[1:3], 16) / 255.0
    g = int(hex_color[3:5], 16) / 255.0
    b = int(hex_color[5:7], 16) / 255.0
    parts = [f"red: {r:.4f}", f"green: {g:.4f}", f"blue: {b:.4f}"]
    if len(hex_color) == 9:
        a = int(hex_color[7:9], 16) / 255.0
        parts.append(f"opacity: {a:.4f}")
    return f"Color({', '.join(parts)})"


def _emit_members(values: dict, render, indent: int) -> list:
    pad = " " * indent
    lines = []
    for name in sorted(values):
        lines.append(f"{pad}static let {name}{render(values[name])}")
    return lines


def render_swift(tokens: dict) -> str:
    """Render the deterministic Tokens.swift source for validated tokens."""
    lines = [HEADER.rstrip("\n"), "", "import SwiftUI", "", "enum Tokens {"]
    colors = tokens["colors"]
    lines.append("    enum Colors {")
    for scheme in COLOR_SCHEMES:
        lines.append(f"        enum {scheme.capitalize()} {{")
        lines.extend(
            _emit_members(
                colors,
                lambda c, scheme=scheme: f" = {_swift_color(c[scheme])}",
                indent=12,
            )
        )
        lines.append("        }")
        if scheme != COLOR_SCHEMES[-1]:
            lines.append("")
    lines.append("    }")

    def value_enum(name: str, section: dict, type_annotation: str) -> None:
        lines.append("")
        lines.append(f"    enum {name} {{")
        lines.extend(
            _emit_members(section, lambda v: f": {type_annotation} = {v}", indent=8)
        )
        lines.append("    }")

    value_enum("Spacing", tokens["spacing"], "CGFloat")
    value_enum("Radii", tokens["radii"], "CGFloat")
    value_enum("ControlSizes", tokens["controlSizes"], "CGFloat")

    lines.append("")
    lines.append("    enum Typography {")
    lines.append("        enum FontSize {")
    lines.extend(
        _emit_members(
            tokens["typography"]["fontSize"], lambda v: f": CGFloat = {v}", indent=12
        )
    )
    lines.append("        }")
    lines.append("")
    lines.append("        enum FontWeight {")
    lines.extend(
        _emit_members(
            tokens["typography"]["fontWeight"],
            lambda v: f" = Font.Weight.{FONT_WEIGHTS[v]}",
            indent=12,
        )
    )
    lines.append("        }")
    lines.append("")
    lines.append("        enum LineHeight {")
    lines.extend(
        _emit_members(
            tokens["typography"]["lineHeight"],
            lambda v: f": CGFloat = {_swift_number(v)}",
            indent=12,
        )
    )
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def load_tokens(path: Path) -> dict:
    try:
        with path.open(encoding="utf-8") as stream:
            data = json.load(stream)
    except json.JSONDecodeError as exc:
        raise TokenError(f"{path}: invalid JSON: {exc}") from exc
    return validate_tokens(data)


def check(tokens_path: Path, swift_out: Path) -> int:
    """Exit 0 when swift_out matches the generated output, else 1 + diff."""
    expected = render_swift(load_tokens(tokens_path))
    try:
        actual = swift_out.read_text(encoding="utf-8")
    except FileNotFoundError:
        print(f"error: {swift_out} does not exist — it is stale")
        print(f"regenerate with: python3 {tokens_path.parent.name}/generate.py")
        return 1
    if actual == expected:
        print(f"{swift_out} is up to date")
        return 0
    print(f"error: {swift_out} is stale — regenerate it, do not edit by hand")
    diff = difflib.unified_diff(
        actual.splitlines(keepends=True),
        expected.splitlines(keepends=True),
        fromfile=f"{swift_out} (stale)",
        tofile=f"{swift_out} (regenerated)",
    )
    sys.stdout.writelines(diff)
    return 1


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate Tokens.swift from tokens.json (deterministic)."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the Swift output is up to date; exit 1 with a diff if not",
    )
    parser.add_argument(
        "--swift-out",
        type=Path,
        default=DEFAULT_SWIFT_OUT,
        help=f"path of the generated Swift file (default: {DEFAULT_SWIFT_OUT})",
    )
    args = parser.parse_args(argv)
    tokens_path = HERE / "tokens.json"
    try:
        if args.check:
            return check(tokens_path, args.swift_out)
        source = render_swift(load_tokens(tokens_path))
        args.swift_out.parent.mkdir(parents=True, exist_ok=True)
        # write_bytes keeps output LF-only on every platform (write_text grew
        # a newline= parameter only in Python 3.10; we support stock 3.9).
        args.swift_out.write_bytes(source.encode("utf-8"))
    except TokenError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(f"wrote {args.swift_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
